import { mkdirSync, readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

type TemplateCategory =
  | 'ai-agents'
  | 'workflows'
  | 'web-frameworks'
  | 'databases'
  | 'self-hosted-tools'
  | 'infrastructure'

type Template = {
  slug: string
  url: string
  name: string
  category: TemplateCategory
  description: string
  intents: string[]
  stack: string[]
  free_tier: boolean
  creates: string[]
}

type Manifest = {
  templates: Template[]
}

type SanityTemplate = {
  slug: string
  title: string
  description: string
  stack?: string[]
  tags?: string[]
  sortOrder: number
}

const categoryLabels: Record<TemplateCategory, string> = {
  'ai-agents': 'AI agents',
  workflows: 'Workflows',
  'web-frameworks': 'Web frameworks',
  databases: 'Databases',
  'self-hosted-tools': 'Self-hosted tools',
  infrastructure: 'Infrastructure',
}

const categoryOrder = Object.keys(categoryLabels) as TemplateCategory[]

const scriptDir = dirname(fileURLToPath(import.meta.url))
const skillDir = join(scriptDir, '..')
const assetsDir = join(skillDir, 'assets')
const manifestPath = join(assetsDir, 'templates.json')
const skillPath = join(skillDir, 'SKILL.md')
const referencesDir = join(skillDir, 'references')
const catalogPath = join(referencesDir, 'catalog.md')
const sanityProjectId = 'hvk0tap5'
const sanityDataset = 'production'
const sanityApiVersion = '2024-08-08'

function readManifest(): Manifest {
  return JSON.parse(readFileSync(manifestPath, 'utf8')) as Manifest
}

function validateManifest(manifest: Manifest) {
  if (!Array.isArray(manifest.templates) || manifest.templates.length === 0) {
    throw new Error('templates.json must contain a non-empty templates array.')
  }

  const slugs = new Set<string>()

  for (const template of manifest.templates) {
    const requiredFields: (keyof Template)[] = [
      'slug',
      'url',
      'name',
      'category',
      'description',
      'intents',
      'stack',
      'free_tier',
      'creates',
    ]

    for (const field of requiredFields) {
      if (!(field in template)) {
        throw new Error(`Template ${template.slug ?? '<unknown>'} is missing ${field}.`)
      }
    }

    if (slugs.has(template.slug)) {
      throw new Error(`Duplicate template slug: ${template.slug}.`)
    }

    if (!categoryOrder.includes(template.category)) {
      throw new Error(`Template ${template.slug} uses unknown category ${template.category}.`)
    }

    if (template.intents.length < 3 || template.intents.length > 6) {
      throw new Error(`Template ${template.slug} must include 3 to 6 intents.`)
    }

    slugs.add(template.slug)
  }
}

function writeManifest(manifest: Manifest) {
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8')
}

function cleanText(value: string) {
  return value.replace(/\s*[\u2013\u2014]\s*/g, ' - ').replace(/\s+/g, ' ').trim()
}

function formatList(values: string[]) {
  return values.map(cleanText).join(', ')
}

function buildTemplateEntry(template: Template) {
  return [
    `#### ${cleanText(template.name)}`,
    '',
    `- URL: ${template.url}`,
    `- Description: ${cleanText(template.description)}`,
    `- Match intents: ${template.intents.map((intent) => `\`${cleanText(intent)}\``).join('; ')}`,
    `- Stack: ${formatList(template.stack) || 'Not specified'}`,
    `- Creates: ${formatList(template.creates)}`,
    `- Free tier: ${template.free_tier ? 'yes' : 'no'}`,
  ].join('\n')
}

function buildCatalog(manifest: Manifest) {
  const lines: string[] = [
    '# Render template catalog',
    '',
    '<!-- This file is generated by scripts/generate.ts. Edit assets/templates.json, then run npm run generate. -->',
    '',
    'Read this catalog when a user asks for a starter, template, or one-click deployable app that might map to Render templates.',
    '',
  ]

  for (const category of categoryOrder) {
    const templates = manifest.templates.filter((template) => template.category === category)
    if (templates.length === 0) continue

    lines.push(`### ${categoryLabels[category]}`, '')
    lines.push(...templates.map(buildTemplateEntry).flatMap((entry) => [entry, '']))
  }

  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n')}`
}

