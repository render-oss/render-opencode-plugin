function generate(manifest: Manifest) {
  validateManifest(manifest)
  mkdirSync(referencesDir, { recursive: true })
  writeFileSync(skillPath, buildSkill(), 'utf8')
  writeFileSync(catalogPath, buildCatalog(manifest), 'utf8')
}

function getRefreshQuery() {
  return `*[_type == "template"] | order(coalesce(sortOrder,0) desc, title asc){
    title,
    description,
    "slug": slug.current,
    stack,
    tags,
    "sortOrder": coalesce(sortOrder,0)
  }`
}

function getRefreshUrl() {
  const query = encodeURIComponent(getRefreshQuery())
  return `https://${sanityProjectId}.api.sanity.io/v${sanityApiVersion}/data/query/${sanityDataset}?query=${query}`
}

function inferCategory(template: SanityTemplate): TemplateCategory {
  const tags = new Set(template.tags ?? [])
  const stack = new Set(template.stack ?? [])
  const slug = template.slug

  if (
    tags.has('ai') ||
    tags.has('ai-agent') ||
    tags.has('llm') ||
    tags.has('mcp') ||
    tags.has('rag') ||
    tags.has('voice')
  ) {
    return 'ai-agents'
  }

  if (slug.includes('workflow')) return 'workflows'

  if (
    ['django', 'fastapi', 'laravel', 'nextjs-hello-world'].includes(slug) ||
    stack.has('nextjs') ||
    stack.has('fastapi') ||
    stack.has('flask')
  ) {
    return 'web-frameworks'
  }

  if (tags.has('database') || ['mysql', 'mongodb', 'postgresql-s3-backups'].includes(slug)) {
    return 'databases'
  }

  if (tags.has('cms') || tags.has('integration') || ['n8n', 'tailscale'].includes(slug)) {
    return 'self-hosted-tools'
  }

  return 'infrastructure'
}

function createDefaultIntents(template: SanityTemplate) {
  const name = cleanText(template.title)
  const slugPhrase = template.slug.replace(/-/g, ' ')
  const tags = new Set(template.tags ?? [])
  const stack = new Set(template.stack ?? [])

  if (tags.has('mcp')) {
    return [
      `deploy ${name}`,
      `build an MCP server like ${name}`,
      `create a Model Context Protocol starter`,
      `host MCP tools on Render`,
    ]
  }

  if (tags.has('ai') || tags.has('ai-agent') || tags.has('llm')) {
    return [
      `deploy ${name}`,
      `build an AI app like ${name}`,
      `host an AI starter on Render`,
      `create a ${slugPhrase} template`,
    ]
  }

  if (tags.has('database')) {
    return [
      `deploy ${name} on Render`,
      `host ${name}`,
      `create a ${slugPhrase} database service`,
      `run ${name} with persistent storage`,
    ]
  }

  if (tags.has('cms') || tags.has('blog')) {
    return [
      `deploy ${name} on Render`,
      `self host ${name}`,
      `run a ${slugPhrase} CMS`,
      `host a blog or publishing platform`,
    ]
  }

  if (tags.has('static-site')) {
    return [
      `deploy ${name} on Render`,
      `host a ${slugPhrase} static site`,
      `create a static site starter`,
      `publish a ${name} site`,
    ]
  }

  if (stack.has('express') || stack.has('flask') || stack.has('go') || stack.has('rust')) {
    return [
      `deploy ${name} on Render`,
      `host a ${slugPhrase} app`,
      `create a ${name} starter`,
      `build a web service with ${name}`,
    ]
  }

  return [
    `deploy ${name} on Render`,
    `host ${name}`,
    `create a ${slugPhrase} starter`,
  ]
}

function inferCreates(template: SanityTemplate) {
  const tags = new Set(template.tags ?? [])
  const slug = template.slug

  if (tags.has('static-site')) return ['static site']
  if (slug.includes('backup')) return ['cron job']
  if (
    tags.has('database') ||
    ['mysql', 'mongodb', 'elasticsearch', 'rabbitmq', 'minio'].includes(slug)
  ) {
    return ['private service', 'disk']
  }
  if (slug.includes('workflow')) return ['web service', 'workflow service']
  return ['web service']
}

function mergeTemplate(template: SanityTemplate, existing?: Template): Template {
  return {
    slug: template.slug,
    url: `https://render.com/templates/${template.slug}`,
    name: cleanText(template.title),
    category: existing?.category ?? inferCategory(template),
    description: cleanText(template.description),
    intents: existing?.intents ?? createDefaultIntents(template),
    stack: template.stack?.map(cleanText) ?? existing?.stack ?? [],
    free_tier: existing?.free_tier ?? false,
    creates: existing?.creates ?? inferCreates(template),
  }
}

async function refresh() {
  const existingManifest = readManifest()
  validateManifest(existingManifest)
  const existingBySlug = new Map(
    existingManifest.templates.map((template) => [template.slug, template])
  )

  const response = await fetch(getRefreshUrl())
  if (!response.ok) {
    throw new Error(`Failed to fetch Sanity templates: ${response.status} ${response.statusText}`)
  }

  const body = (await response.json()) as { result?: SanityTemplate[]; error?: unknown }
  if (body.error || !Array.isArray(body.result)) {
    throw new Error(`Unexpected Sanity response: ${JSON.stringify(body.error ?? body)}`)
  }

  const refreshed: Manifest = {
    templates: body.result
      .filter((template) => template.slug)
      .map((template) => mergeTemplate(template, existingBySlug.get(template.slug))),
  }

  validateManifest(refreshed)
  writeManifest(refreshed)
  generate(refreshed)
}

async function main() {
  const command = process.argv[2] ?? 'generate'

  if (command === 'generate') {
    generate(readManifest())
    return
  }

  if (command === 'refresh') {
    await refresh()
    return
  }

  throw new Error(`Unknown command "${command}". Use "generate" or "refresh".`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
